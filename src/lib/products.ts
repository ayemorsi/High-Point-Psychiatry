// The one place the storefront reads the catalog. Swap this body for your commerce API.
export const getProducts = cache(async (): Promise<Product[]> =>
  catalog.map((product) => ({
    ...product,
    covers: product.contains
      ? product.contains.flatMap(
          (slug) => catalog.find((item) => item.slug === slug)?.step ?? []
        )
      : [product.step],
  }))
)

export async function getProduct(slug: string) {
  return (await getProducts()).find((product) => product.slug === slug)
}

export async function getProductsByStep(step: StepId) {
  return (await getProducts()).filter((product) => product.step === step)
}
